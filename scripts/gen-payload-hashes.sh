#!/bin/bash
# Write internal/embedded/<outfile>: the SHA-256 of each helper that is about to
# be embedded, as a Go constant table (see internal/embedded.payloadHashes).
# Called by scripts/build.sh and scripts/build-windows.sh after they copied the
# helpers into internal/embedded/payload/, so the hashes describe exactly the
# bytes go:embed will carry.
#
#   scripts/gen-payload-hashes.sh <go build constraint> <outfile> <helper>...
set -euo pipefail
cd "$(dirname "$0")/.."

constraint=$1 out=internal/embedded/$2
shift 2
sha256() {
    if command -v shasum >/dev/null; then shasum -a 256 "$1"; else sha256sum "$1"; fi | cut -d' ' -f1
}
{
    echo "// Code generated by scripts/gen-payload-hashes.sh; DO NOT EDIT."
    echo
    echo "//go:build $constraint"
    echo
    echo "package embedded"
    echo
    echo "var payloadHashes = map[string]string{"
    for f in "$@"; do
        printf '\t"%s": "%s",\n' "$f" "$(sha256 "internal/embedded/payload/$f")"
    done
    echo "}"
} >"$out"
gofmt -w "$out" # aligns the map values; go is installed or the build below would not run
